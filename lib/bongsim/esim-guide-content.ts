export type GuideTab = "precheck" | "iphone" | "android";

export interface GuideBlock {
  /** 소제목(선택) */
  heading?: string;
  /** 본문 문단들 */
  paras?: string[];
  /** 불릿 목록 */
  bullets?: string[];
  /** 강조/주의 한 줄(amber callout 등으로 렌더 권장) */
  note?: string;
  /** image_assets entity_id (guideKey) — esim-guide-image-manifest.ts 와 1:1 */
  image?: string;
  /** note 아래 봉투어 CS(카톡) 버튼 블록 */
  showBongsimCs?: boolean;
}

export type EsimGuideImageMap = Record<
  string,
  { url: string; alt: string; width?: number; height?: number }
>;

export interface GuideStep {
  n: number;
  title: string;
  blocks: GuideBlock[];
}

export interface GuideFaq {
  q: string;
  a: string;
  /** 답변 아래 봉투어 CS(카톡) 버튼 블록 */
  showBongsimCs?: boolean;
}

